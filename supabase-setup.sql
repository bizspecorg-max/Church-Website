drop policy if exists "Public can submit contact" on public.contacts;
create policy "Public can submit contact" on public.contacts for insert with check (true);

drop policy if exists "Public can submit donation" on public.donations;
create policy "Public can submit donation" on public.donations for insert with check (true);

drop policy if exists "Public can register partner" on public.partners;
