-- ========== 1. TABLES ==========
create table if not exists public.videos (
  id          bigint generated by default as identity primary key,
  title       text not null,
  section     text default 'Recent Messages',
  category    text,
  youtube_url text not null,
  description text,
  play_mode   text default 'inline',
  sort_order  int  default 0,
  published   boolean default true,
  created_at  timestamptz default now()
);
-- in case the table already existed without these:
alter table public.videos add column if not exists section   text default 'Recent Messages';
alter table public.videos add column if not exists play_mode text default 'inline';

create table if not exists public.hero_slides (
  id bigint generated by default as identity primary key,
  image_url text not null, headline text, sort_order int default 0,
  published boolean default true, created_at timestamptz default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text, email text, subject text, message text, created_at timestamptz default now()
);

create table if not exists public.donations (
  id bigint generated by default as identity primary key,
  name text, email text, phone text, amount numeric, status text, created_at timestamptz default now()
);

create table if not exists public.partners (
  id bigint generated by default as identity primary key,
  name text, email text, phone text, country text, amount numeric, status text, created_at timestamptz default now()
);

create table if not exists public.admins (
  email text primary key, created_at timestamptz default now()
);

create table if not exists public.site_content (
  key text primary key, value text, updated_at timestamptz default now()
);

create table if not exists public.testimonials (
  id         bigint generated by default as identity primary key,
  quote      text,
  name       text,
  location   text,
  photo_url  text,
  sort_order int default 0,
  published  boolean default true,
  created_at timestamptz default now()
);

