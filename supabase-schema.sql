-- ---------- VIDEOS (Messages that play on the site) ----------
create table if not exists public.videos (
  id          bigint generated by default as identity primary key,
  title       text not null,
  category    text,                 -- shown as the small label (e.g. "Praise & Worship")
  youtube_url text not null,        -- full link, e.g. https://www.youtube.com/watch?v=XXXX
  description text,
  sort_order  int  default 0,
  published   boolean default true,
  created_at  timestamptz default now()
);

alter table public.videos enable row level security;

-- Anyone (anon) can READ published videos. Only the dashboard / service role can write.
drop policy if exists "Public can read published videos" on public.videos;
create policy "Public can read published videos"
  on public.videos for select
  using (published = true);

