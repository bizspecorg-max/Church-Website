-- ---------- CONTACTS (contact form submissions) ----------
create table if not exists public.contacts (
  id         bigint generated by default as identity primary key,
  name       text,
  email      text,
  subject    text,
  message    text,
  created_at timestamptz default now()
);

alter table public.contacts enable row level security;

-- The public website may INSERT a message, but cannot read others' messages.
drop policy if exists "Public can submit contact" on public.contacts;
create policy "Public can submit contact"
  on public.contacts for insert
  with check (true);

-- ---------- DONATIONS (lead capture for every give attempt) ----------
create table if not exists public.donations (
  id         bigint generated by default as identity primary key,
  name       text,
  email      text,
  phone      text,
  amount     numeric,
  status     text,
  created_at timestamptz default now()
);

alter table public.donations enable row level security;

drop policy if exists "Public can submit donation" on public.donations;
create policy "Public can submit donation"
  on public.donations for insert
  with check (true);

